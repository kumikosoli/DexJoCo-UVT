"""Join official DexJoCo LeRobot v3 data with replayed MuJoCo tactile data.

This is the production path for the RLDX tactile ablation dataset.  It keeps
the official RGB, state and action trajectories, and adds only the *current*
pre-action tactile tensor generated by a data-only MuJoCo replay.  In
particular, it never consumes ``next_tactile_gt.*``.

The join is deliberately fail-closed.  Lexicographic raw-episode order gives
the proposed official episode index, but that proposal is accepted only when
all of the following evidence agrees for every selected episode:

* ``start_idx = raw_length - official_length``;
* ``start_idx`` is the left index of the first adjacent action change;
* official action equals the cached
  ``float32(raw.action_rotvec[start_idx:])`` bitwise;
* official state equals ``float32(raw.state[start_idx:, :23])`` bitwise;
* a unique replay episode equals the complete canonical action obtained by
  converting the raw quaternion action to rotvec; and
* all recorded replay state rows pass per-field trajectory tolerances;
* replay row zero equals the complete 31-dimensional raw initial state after
  both are normalized to float32, and replay length equals raw length;
* replay provenance proves that it was produced in data-only mode without
  RGB, video, or depth outputs; and
* its current ``tactile_gt.taxel_force_local`` has the raw length and the v3
  tactile metadata contract.

This checks recorded observations, not unrecorded solver state or changing
object poses absent from the source state. Prefer synchronized replay RGB
for new datasets; successful task replay alone does not establish alignment.

Cached and canonical raw actions must normally be bitwise identical.  The one
accepted legacy representation anomaly has a much narrower proof: mismatch
rows must be exactly ``0..start_idx``; the cached prefix must be all zero; the
canonical prefix must be one constant, nonzero pose; equality must resume after
``start_idx``; and only output row zero may differ between the official cached
tail and the canonical replay sequence.  The complete canonical sequence must
still identify one and only one replay episode.

Official v3 videos are split at their recorded per-episode keyframes.  The
default output transcodes those exact official slices to H.264 because the
RLDX v1.0.2 OpenCV backend on the training image cannot decode independently
stream-copied AV1 episode files.  This is a video-container/codec conversion,
not a MuJoCo re-render; both ablation arms consume the same converted RGB.
Packet-preserving ``copy`` mode remains available for environments with a
working AV1 loader.
"""

